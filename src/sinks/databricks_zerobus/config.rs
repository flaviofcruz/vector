/// Authentication configuration for Databricks.
#[configurable_component]
#[derive(Clone, Debug)]
#[serde(tag = "strategy", rename_all = "snake_case", deny_unknown_fields)]
#[allow(clippy::large_enum_variant)] // config value built once; size irrelevant
pub enum DatabricksAuthentication {
    /// Authenticate using OAuth 2.0 client credentials.
    #[serde(rename = "oauth")]
    OAuth {
        /// OAuth 2.0 client ID.
        #[configurable(metadata(docs::examples = "${DATABRICKS_CLIENT_ID}"))]
        #[configurable(metadata(docs::examples = "abc123..."))]
        client_id: SensitiveString,

        /// OAuth 2.0 client secret.
        #[configurable(metadata(docs::examples = "${DATABRICKS_CLIENT_SECRET}"))]
        #[configurable(metadata(docs::examples = "secret123..."))]
        client_secret: SensitiveString,
    },

    /// Authenticate via Login service using mTLS bootstrap.
    ///
    /// Used by logging-agent to mint signed and unsigned principal contexts by authenticating
    /// as a System Service Principal via s2s-proxy.
    #[serde(rename = "login_service")]
    LoginService(crate::databricks_auth::LoginServiceAuthConfig),
}

/// Schema source configuration for defining table schema.
///
/// The schema can be provided as either:
/// - A path to a protobuf descriptor file (.desc or .pb)
/// - Dynamically fetched from the Unity Catalog table
#[configurable_component]
#[derive(Clone, Debug)]
#[serde(tag = "type", rename_all = "snake_case")]
#[derive(Default)]
pub enum SchemaSource {
    /// Path to a protobuf descriptor file.
    ///
    /// The file should contain a serialized FileDescriptorSet or DescriptorProto.
    /// These files are typically generated by protoc with the --descriptor_set_out flag.
    ///
    /// Example:
    /// ```sh
    /// protoc --descriptor_set_out=schema.desc --include_imports your_schema.proto
    /// ```
    Path {
        /// Path to the descriptor file.
        #[configurable(metadata(docs::examples = "/path/to/schema.desc"))]
        #[configurable(metadata(docs::examples = "./schema.pb"))]
        path: String,

        /// The message type to use from the descriptor file.
        #[configurable(metadata(docs::examples = "package.Message"))]
        message_type: String,
    },

    /// Dynamically fetch schema from Unity Catalog table.
    ///
    /// This will query the Unity Catalog API to get the table schema and
    /// automatically generate a protobuf descriptor from it.
    /// Uses the same authentication credentials as the sink.
    #[serde(rename = "unity_catalog")]
    #[default]
    UnityCatalog,
}

/// Arrow IPC compression codec for Zerobus Arrow Flight payloads.
#[configurable_component]
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum Compression {
    /// No compression.
    #[default]
    None,
    /// LZ4 frame compression.
    Lz4Frame,
    /// Zstandard compression.
    Zstd,
}

impl From<Compression> for databricks_zerobus_ingest_sdk::ArrowCompression {
    fn from(value: Compression) -> Self {
        match value {
            Compression::None => Self::Uncompressed,
            Compression::Lz4Frame => Self::IpcLz4,
            Compression::Zstd => Self::IpcZstd,
        }
    }
}

/// Whole-message gRPC compression codec for Zerobus Arrow Flight payloads.
#[configurable_component]
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum GrpcCompression {
    /// No whole-message gRPC compression.
    #[default]
    None,
    /// Zstandard compression of each whole gRPC request message.
    Zstd,
}

impl From<GrpcCompression> for databricks_zerobus_ingest_sdk::ArrowCompression {
    fn from(value: GrpcCompression) -> Self {
        match value {
            GrpcCompression::None => Self::Uncompressed,
            GrpcCompression::Zstd => Self::GrpcZstd,
        }
    }
}

/// Zerobus stream configuration options.
///
/// This is a thin wrapper around the SDK's `ArrowStreamConfigurationOptions` with
/// Vector-specific configuration attributes and custom defaults suitable for Vector's use case.
#[configurable_component]
#[derive(Clone, Debug)]
#[serde(deny_unknown_fields)]
pub struct ZerobusStreamOptions {
    /// Timeout in milliseconds for flush operations.
    #[serde(default = "default_flush_timeout_ms")]
    #[configurable(metadata(docs::examples = 30000))]
    pub flush_timeout_ms: u64,

    /// Timeout in milliseconds for server acknowledgments.
    #[serde(default = "default_server_ack_timeout_ms")]
    #[configurable(metadata(docs::examples = 60000))]
    pub server_lack_of_ack_timeout_ms: u64,

    /// Arrow IPC compression for Flight payloads. Defaults to no compression.
    #[configurable(derived)]
    #[serde(default, skip_serializing_if = "crate::serde::is_default")]
    pub compression: Compression,

    /// Whole-message gRPC compression for Flight payloads.
    ///
    /// Compresses each entire gRPC request message, including the IPC header and
    /// alignment padding that IPC `compression` leaves raw, which sends fewer bytes
    /// for wide or sparse schemas at the cost of more client CPU. Buffers are sent
    /// without IPC compression. Mutually exclusive with `compression`. Defaults to no
    /// compression.
    #[configurable(derived)]
    #[serde(default, skip_serializing_if = "crate::serde::is_default")]
    pub grpc_compression: GrpcCompression,

    /// Number of Arrow Flight streams (lanes) the sink spreads this table's batches across.
    ///
    /// The Zerobus server processes each stream strictly serially, so one stream caps a
    /// pod's throughput for wide tables regardless of request concurrency. With more than
    /// one lane, whole batches are distributed round-robin across independent streams, so
    /// batches are no longer written in submission order. Each batch is still acknowledged
    /// only once durable on its own lane.
    ///
    /// Values above 1 use the SDK's Beta multiplexed Arrow stream: a terminal failure on any
    /// lane closes and recreates all lanes, and a lane that cannot accept a batch within 30
    /// seconds fails that request with a retryable error. The default of 1 keeps the
    /// single-stream path.
    ///
    /// Each lane only progresses while a request is in flight on it, so keep this at or
    /// below `request.concurrency` (ideally equal); extra lanes sit idle.
    #[serde(default = "default_multiplexed_streams")]
    #[configurable(metadata(docs::examples = 1))]
    #[configurable(metadata(docs::examples = 4))]
    pub multiplexed_streams: usize,
}

/// Upper bound on `multiplexed_streams`; the SDK encodes the lane index in 6 bits.
pub const MAX_MULTIPLEXED_STREAMS: usize = 64;

impl ZerobusStreamOptions {
    /// The single SDK compression mode these options select.
    ///
    /// Callers must have passed `validate`, which rejects setting both codecs.
    pub fn arrow_compression(&self) -> databricks_zerobus_ingest_sdk::ArrowCompression {
        match self.grpc_compression {
            GrpcCompression::None => self.compression.into(),
            grpc => grpc.into(),
        }
    }
}

impl Default for ZerobusStreamOptions {
    fn default() -> Self {
        Self {
            flush_timeout_ms: default_flush_timeout_ms(),
            server_lack_of_ack_timeout_ms: default_server_ack_timeout_ms(),
            compression: Compression::None,
            grpc_compression: GrpcCompression::None,
            multiplexed_streams: default_multiplexed_streams(),
        }
    }
}

/// Configuration for the Databricks Zerobus sink.
#[configurable_component(sink(
    "databricks_zerobus",
    "Stream observability data to Databricks Unity Catalog via Zerobus."
))]
#[derive(Clone, Debug)]
#[serde(deny_unknown_fields)]
pub struct ZerobusSinkConfig {
    /// The Zerobus ingestion endpoint URL.
    ///
    /// This should be the full URL to the Zerobus ingestion service.
    #[configurable(metadata(docs::examples = "https://ingest.dev.databricks.com"))]
    #[configurable(metadata(docs::examples = "https://ingest.prod.databricks.com"))]
    pub ingestion_endpoint: String,

    /// Optional TLS server name for the Zerobus ingestion connection.
    ///
    /// Overrides SNI and the name verified against the server certificate, without
    /// changing the ingestion endpoint or HTTP authority. Applies to both auth
    /// strategies. If unset, the SDK uses the ingestion endpoint's hostname.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ingestion_domain_name: Option<String>,

    /// The Unity Catalog table name to write to.
    ///
    /// This should be in the format `catalog.schema.table`.
    #[configurable(metadata(docs::examples = "logging_platform.my_team.logs"))]
    #[configurable(metadata(docs::examples = "main.default.vector_logs"))]
    pub table_name: String,

    /// The Unity Catalog endpoint URL.
    ///
    /// Public workspace URL for OAuth; internal managed-catalog gRPC URL for Login auth.
    #[configurable(metadata(
        docs::examples = "https://dbc-e2f0eb31-2b0e.staging.cloud.databricks.com"
    ))]
    #[configurable(metadata(docs::examples = "https://your-workspace.cloud.databricks.com"))]
    pub unity_catalog_endpoint: String,

    /// Databricks authentication configuration.
    #[configurable(derived)]
    pub auth: DatabricksAuthentication,

    /// Custom identifier appended to the `user-agent` header sent to Databricks.
    ///
    /// The header always includes `Vector/<version>`; when set, this value is
    /// appended after it (e.g. `my-service/1.2`).
    #[serde(default)]
    #[configurable(metadata(docs::examples = "my-service/1.2"))]
    pub user_agent: Option<String>,

    /// Extra static headers attached to every Zerobus gRPC request.
    ///
    /// Applied on both auth strategies. Names must be lowercase (gRPC metadata
    /// keys are). Reserved auth headers (`authorization`,
    /// `x-databricks-zerobus-table-name`, `user-agent` — controlled via
    /// `user_agent`) and gRPC transport headers (`content-type`, `te`, any
    /// `grpc-*`) cannot be set here.
    ///
    /// `x-databricks-app-instance-name` may be set here to route traffic to a
    /// personal pod deployment (dev/staging). On `login_service` auth a value
    /// set here takes precedence over the `ZEROBUS_APP_INSTANCE_NAME` env var.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub custom_headers: BTreeMap<String, String>,

    /// Schema definition for the table.
    ///
    /// Defaults to fetching the schema dynamically from Unity Catalog.
    /// Can be omitted from the configuration entirely to use the default.
    #[configurable(derived)]
    #[serde(default)]
    pub schema: SchemaSource,

    /// Zerobus stream configuration options.
    #[serde(default)]
    pub stream_options: ZerobusStreamOptions,

    /// The batch encoding configuration for encoding events in batches.
    ///
    /// Defaults to protobuf batch encoding, which serializes each event
    /// individually as a protobuf message.
    #[configurable(derived)]
    #[serde(default = "default_batch_encoding")]
    pub batch_encoding: BatchSerializerConfig,

    /// Maximum number of batches encoded on blocking workers at once, shared by this sink's requests.
    ///
    /// Omit to encode inline. This limit is independent of request concurrency: a worker is released
    /// after encoding, while the request remains in flight until acknowledgment. Running encoding
    /// jobs retain their worker permit if their caller is cancelled.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub encoding_concurrency: Option<NonZeroUsize>,

    #[configurable(derived)]
    #[serde(default)]
    pub batch: BatchConfig<RealtimeSizeBasedDefaultBatchSettings>,

    #[configurable(derived)]
    #[serde(default)]
    pub request: TowerRequestConfig,

    /// Reload the schema from Unity Catalog and retry when the ingestion server
    /// rejects the sink's Arrow schema as stale, instead of dropping the batch
    /// until the pod is restarted.
    ///
    /// Off by default: when disabled, a schema rejection stays a non-retryable
    /// drop, exactly as before. Enable it to let a running sink pick up a table
    /// whose schema was widened underneath it.
    #[serde(default)]
    pub recover_from_schema_rejection: bool,

    #[configurable(derived)]
    #[serde(
        default,
        deserialize_with = "crate::serde::bool_or_struct",
        skip_serializing_if = "crate::serde::is_default"
    )]
    pub acknowledgements: AcknowledgementsConfig,
}

